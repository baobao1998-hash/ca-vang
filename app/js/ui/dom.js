export function icon(name, size = 20) {
  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "1.9");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  for (const d of ICONS[name] || []) {
    const p = document.createElementNS(SVG_NS, "path");
    p.setAttribute("d", d);
    svg.append(p);
  }
  return svg;
}

/** Xoá sạch rồi vẽ lại nội dung của một phần tử. */
export function mount(parent, ...children) {
  parent.replaceChildren();
  appendChildren(parent, children);
}

let toastTimer;
/** Thông báo nhỏ nổi lên rồi tự tắt. type: "ok" | "error" */
export function toast(message, type = "ok", ms = 2600) {
  let box = document.getElementById("toast-box");
  if (!box) {
    box = h("div", { id: "toast-box", role: "status", "aria-live": "polite" });
    document.body.append(box);
  }
  const t = h("div", { class: `toast toast-${type} glass-strong` }, icon(type === "error" ? "info" : "check", 18), h("span", null, message));
  box.replaceChildren(t);
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.remove(), ms);
}
