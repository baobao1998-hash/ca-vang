// Tạo phần tử an toàn: KHÔNG dùng innerHTML. Mọi chữ đều đi qua textContent / createTextNode.
const SVG_NS = "http://www.w3.org/2000/svg";

/**
 * h("div", {class:"a", onclick: fn, style:{color:"red"}}, "chữ", h("b", null, "đậm"))
 * Thuộc tính on* gắn sự kiện; false/null/undefined bị bỏ qua.
 */
export function h(tag, attrs, ...children) {
  const el = document.createElement(tag);
  applyAttrs(el, attrs);
  appendChildren(el, children);
  return el;
}

function applyAttrs(el, attrs) {
  if (!attrs) return;
  for (const [k, v] of Object.entries(attrs)) {
    if (v === false || v == null) continue;
    if (k === "class") el.className = v;
    else if (k === "style" && typeof v === "object") Object.assign(el.style, v);
    else if (k === "dataset") Object.assign(el.dataset, v);
    else if (k.startsWith("on") && typeof v === "function") el.addEventListener(k.slice(2).toLowerCase(), v);
    else el.setAttribute(k, v === true ? "" : String(v));
  }
}

function appendChildren(el, children) {
  for (const c of children.flat(Infinity)) {
    if (c === false || c == null) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
}

